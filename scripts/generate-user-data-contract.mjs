import fs from 'node:fs'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const source = fileURLToPath(new URL('../apps/web/app/utils/userData.ts', import.meta.url))
const target = fileURLToPath(new URL('../cloudfunctions/cook-user-data/user-data.cjs', import.meta.url))
const output = `// Generated by scripts/generate-user-data-contract.mjs; edit apps/web/app/utils/userData.ts.\n${ts.transpileModule(fs.readFileSync(source, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
}).outputText}`
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output)
    throw new Error('User data contract is stale; run node scripts/generate-user-data-contract.mjs')
}
else {
  fs.writeFileSync(target, output)
}
